import { describe, expect, it } from 'vitest'
import { makeBed, OWNED_BIRDIE } from './birdies'
import { bomPlainText, buildBom } from './bom'
import { DEFAULTS, PRESETS, sanitise } from './model'
import { V2_BIRD_NET_AUD, V2_COMMON_AUD, V2_SHADE_AUD } from './v2'
import { BIRDIES_SHIP_AUD, birdiesBedAud, SOIL_M3_AUD } from './prices'

describe('buildBom', () => {
  it('counts 13 hoops of pipe for the 12 × 6 preset', () => {
    const preset = PRESETS.find((p) => p.id === '12x6')
    const bom = buildBom(sanitise(preset!.patch))
    expect(bom.geo.hoopCount).toBe(13)
    const hoop = bom.lines.find((l) => l.id === 'hoop-pipe')
    expect(hoop?.exactM).toBeGreaterThan(13 * 6)
    expect(hoop?.buy).toMatch(/coil/)
    expect(bom.lines.find((l) => l.id === 'door-frame')).toBeDefined()
    expect(bom.lines.find((l) => l.id === 'mesh-gate')).toBeUndefined()
    expect(bom.lines.find((l) => l.id === 'tomato-trellis')).toBeUndefined()
  })

  it('bills the Marek v2 bird-net cage at the spec total', () => {
    const bom = buildBom(DEFAULTS)
    expect(bom.geo.hoopCount).toBe(8)
    const posts = bom.lines.find((l) => l.id === 'posts')
    expect(posts?.qty).toBe(12)
    expect(posts?.unitAud).toBe(29.5)
    expect(posts?.lineAud).toBeCloseTo(354, 2)
    expect(posts?.buy).toMatch(/already have 4/)
    expect(posts?.spec).toMatch(/Galstar MaxY/)
    const battens = bom.lines.find((l) => l.id === 'battens')
    expect(battens?.qty).toBe(19)
    expect(battens?.lineAud).toBeCloseTo(406.98, 2)
    expect(battens?.exact).toMatch(/7 lines × 2/)
    expect(bom.lines.find((l) => l.id === 'hoop-pipe')?.qty).toBe(1)
    expect(bom.lines.find((l) => l.id === 'hoop-pipe')?.lineAud).toBeCloseTo(519, 2)
    expect(bom.lines.find((l) => l.id === 'hoop-pipe')?.note).toMatch(/No ridge pipe/)
    expect(bom.lines.find((l) => l.id === 'sleeper')?.qty).toBe(14)
    expect(bom.lines.find((l) => l.id === 'sleeper')?.note).toMatch(/150 mm buried, 50 mm above/)
    expect(bom.lines.find((l) => l.id === 'end-posts')?.estimate).toBe(true)
    expect(bom.lines.find((l) => l.id === 'end-posts')?.lineAud).toBeCloseTo(180, 2)
    expect(bom.lines.find((l) => l.id === 'door-concrete')?.qty).toBe(12)
    expect(bom.lines.find((l) => l.id === 'mesh-gate')?.lineAud).toBeCloseTo(176, 2)
    expect(bom.lines.find((l) => l.id === 'mesh-gate')?.exact).toMatch(/opens outward/)
    expect(bom.lines.find((l) => l.id === 'ironmongery')?.estimate).toBe(true)
    expect(bom.lines.find((l) => l.id === 'ironmongery')?.note).toMatch(/ALLOWANCE/)
    expect(bom.lines.find((l) => l.id === 'dpc')?.estimate).toBe(true)
    expect(bom.lines.find((l) => l.id === 'wall-mesh')?.qty).toBe(6)
    expect(bom.lines.find((l) => l.id === 'wall-mesh')?.exactM).toBeCloseTo(28.5, 2)
    expect(bom.lines.find((l) => l.id === 'teks')?.qty).toBe(3)
    expect(bom.lines.find((l) => l.id === 'bolts')?.qty).toBe(1)
    expect(bom.lines.find((l) => l.id === 'cable-ties')?.qty).toBe(5)
    expect(bom.lines.find((l) => l.id === 'cover')?.lineAud).toBeCloseTo(75.99, 2)
    expect(bom.lines.find((l) => l.id === 'hog-rings')?.inTotal).toBe(false)
    const trellis = bom.lines.find((l) => l.id === 'tomato-trellis')
    expect(trellis?.buy).toMatch(/already have/)
    expect(trellis?.inTotal).toBe(false)
    expect(trellis?.spec).toMatch(/Ultrapost/)
    expect(bom.lines.find((l) => l.id === 'skirt')).toBeUndefined()
    expect(bom.lines.find((l) => l.id === 'shoulder-wire')).toBeUndefined()
    expect(bom.lines.find((l) => l.id === 'gripples')).toBeUndefined()
    expect(bom.lines.find((l) => l.id === 'stays')).toBeUndefined()
    expect(bom.lines.find((l) => l.id === 'anchors')).toBeUndefined()
    expect(bom.lines.find((l) => l.id === 'ridge')).toBeUndefined()
    const estimates = bom.lines.filter((l) => l.estimate)
    expect(estimates.reduce((sum, line) => sum + line.lineAud, 0)).toBeCloseTo(245, 2)
    expect(bom.priceNote).toMatch(/\$245\.00/)
    expect(bom.priceNote).toMatch(/freight/)
    const common =
      bom.totals.cageAud - (posts?.lineAud ?? 0) - (bom.lines.find((l) => l.id === 'cover')?.lineAud ?? 0)
    expect(common).toBeCloseTo(V2_COMMON_AUD, 2)
    expect(bom.totals.cageAud).toBeCloseTo(V2_BIRD_NET_AUD, 2)
    const text = JSON.stringify(bom.lines)
    expect(text).not.toMatch(/Gripple/)
    expect(text).not.toMatch(/chicken wire/i)
    expect(bomPlainText(DEFAULTS, bom)).toMatch(/\(estimate\)/)
    expect(bom.totals.hoopPipeM).toBeCloseTo(64.8, 1)
    expect(bom.totals.netM2).toBeGreaterThan(40)
  })

  it('bills shade cloth at its own total, still 19 battens', () => {
    const bom = buildBom(sanitise({ cover: 'shade-30', hoopSpacing: 1.25 }))
    expect(bom.geo.hoopCount).toBe(9)
    expect(bom.lines.find((l) => l.id === 'posts')?.qty).toBe(14)
    expect(bom.lines.find((l) => l.id === 'posts')?.lineAud).toBeCloseTo(413, 2)
    expect(bom.lines.find((l) => l.id === 'cover')?.qty).toBe(2)
    expect(bom.lines.find((l) => l.id === 'cover')?.lineAud).toBeCloseTo(347.76, 2)
    expect(bom.lines.find((l) => l.id === 'battens')?.qty).toBe(19)
    expect(bom.lines.find((l) => l.id === 'teks')?.qty).toBe(3)
    expect(bom.totals.cageAud).toBeCloseTo(V2_SHADE_AUD, 2)
  })

  it('wall mesh run is perimeter minus door plus joins', () => {
    const bom = buildBom(DEFAULTS)
    const wall = bom.lines.find((l) => l.id === 'wall-mesh')
    expect(wall?.exactM).toBeGreaterThan(2 * (DEFAULTS.length + DEFAULTS.width) - DEFAULTS.doorWidth)
    expect(wall?.buy).toMatch(/roll/)
  })

  it('lists four owned Birdies beds and soil volume', () => {
    const bom = buildBom(DEFAULTS)
    const row = bom.bedLines.find((l) => l.id === 'birdies-1')
    expect(row?.buy).toMatch(/owned/)
    expect(row?.exact).toMatch(/4 bed/)
    expect(row?.inTotal).toBe(false)
    expect(bom.totals.soilM3).toBeGreaterThan(4)
    expect(bom.totals.growM2).toBeCloseTo(4 * 1.22 * 2.44, 1)
  })

  it('plain numbers stay in metres', () => {
    const bom = buildBom(DEFAULTS)
    expect(bom.totals.hoopPipeM).toBeGreaterThan(50)
    expect(bom.totals.netM2).toBeGreaterThan(80)
  })

  it('prices cage separately from owned Birdies (soil only)', () => {
    const bom = buildBom(DEFAULTS)
    expect(bom.lines.some((l) => l.id.startsWith('birdies') || l.id === 'soil')).toBe(false)
    expect(bom.totals.cageAud).toBeGreaterThan(200)
    const soil = bom.bedLines.find((l) => l.id === 'soil')
    expect(soil?.inTotal).toBe(true)
    expect(bom.totals.bedsAud).toBeCloseTo(soil!.lineAud, 2)
    expect(bom.bedLines.find((l) => l.id === 'birdies-ship')).toBeUndefined()
    const hoopLot = bom.lines.find((l) => l.id === 'hoop-pipe')
    expect(hoopLot?.inTotal).toBe(true)
    expect(hoopLot!.lineAud).toBeGreaterThan(0)
  })

  it('prices unowned Birdies beds on the beds list only', () => {
    const extra = makeBed({ ...OWNED_BIRDIE, owned: false, x: 0, z: 0, rot: 0 })
    const bom = buildBom({ ...DEFAULTS, beds: [...DEFAULTS.beds, extra] })
    const buy = bom.bedLines.find((l) => l.id.startsWith('birdies-') && l.inTotal)
    expect(buy?.qty).toBe(1)
    expect(buy?.lineAud).toBeCloseTo(birdiesBedAud(1.22, 2.44, 0.37), 2)
    expect(bom.bedLines.find((l) => l.id === 'birdies-ship')?.lineAud).toBe(BIRDIES_SHIP_AUD)
    const soil = bom.bedLines.find((l) => l.id === 'soil')
    expect(bom.totals.bedsAud).toBeCloseTo(buy!.lineAud + soil!.lineAud + BIRDIES_SHIP_AUD, 2)
    expect(bom.lines.every((l) => !l.id.startsWith('birdies'))).toBe(true)
    expect(soil?.lineAud).toBeCloseTo(5 * 1.22 * 2.44 * 0.37 * SOIL_M3_AUD, 0)
  })
})
